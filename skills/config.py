"""locals.toml: who you actually face.

Top tournament lists are the optimised, funded, fully-teched field. Locals
run budget builds, last format's deck, and rogue piles. Every gauntlet and
every optimizer objective weights by this file rather than by global meta
share -- otherwise you tune perfectly for a room you never sit in.

The file names archetypes the way the `archetypes` command does ("Kewl
Tune"), while deck files and engine results are keyed by filename stem
("kewl-tune"). `slug` reconciles the two so neither side has to care.
"""

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALS = ROOT / "locals.toml"


def slug(name):
    """'Kewl Tune' and 'kewl-tune' both -> 'kewl-tune'."""
    return "-".join(str(name).lower().replace("-", " ").split())


def load(path=None):
    path = Path(path) if path else LOCALS
    if not path.exists():
        return {"meta": {}, "weights": {}}
    with path.open("rb") as fh:
        return tomllib.load(fh)


def weights(path=None, normalise=True):
    """Archetype share, keyed by slug. Normalised to sum to 1 by default."""
    raw = (load(path).get("weights") or {})
    out = {slug(k): float(v) for k, v in raw.items()}
    if normalise and out:
        total = sum(out.values())
        if total:
            out = {k: v / total for k, v in out.items()}
    return out


def weight_for(deck_name, path=None):
    return weights(path).get(slug(deck_name), 0.0)


def coverage(deck_names, path=None):
    """How much of your stated locals meta the measured decks cover.

    A handtrap ranking weighted over 40% of your room is a ranking over
    40% of your room, and should say so.
    """
    w = weights(path)
    have = {slug(d) for d in deck_names}
    covered = sum(v for k, v in w.items() if k in have)
    missing = sorted(k for k in w if k not in have and w[k] > 0)
    return covered, missing


# --- auto-fill from the scrape -------------------------------------------

# The scrape only ever sees decks that TOP a tournament. A locals room is
# not that room: it carries budget builds, last format's deck and rogue
# piles that never place anywhere. Reserving a slice for them is less
# wrong than pretending the field is pure tier 1.
DEFAULT_ROGUE = 0.25


def scraped_shares(conn, fmt=None, top=12):
    """Archetype shares from stored tournament lists, summing to 1.

    Each DECK carries one unit of weight, split equally among its tags.
    Counting tag rows directly would be wrong: lists average 1.66 tags
    each (one carries five), so raw tag counts sum to 166% of the deck
    count and inflate hybrid-heavy archetypes against pure ones. A
    four-engine list is not four opponents.
    """
    rows = conn.execute(
        """SELECT t.deck_id, t.tag FROM deck_tags t
             JOIN decks d ON d.id = t.deck_id
            WHERE (? IS NULL OR d.format = ?)""",
        (fmt, fmt),
    ).fetchall()
    per_deck = {}
    for r in rows:
        per_deck.setdefault(r["deck_id"], []).append(r["tag"])

    weight = {}
    for tags in per_deck.values():
        share = 1.0 / len(tags)
        for tag in tags:
            weight[slug(tag)] = weight.get(slug(tag), 0.0) + share

    total = sum(weight.values()) or 1.0
    ranked = sorted(weight.items(), key=lambda kv: -kv[1])[:top]
    kept = sum(w for _, w in ranked) or 1.0
    return [(name, w / kept) for name, w in ranked], total


def autofill(conn, path=None, top=10, rogue=DEFAULT_ROGUE, fmt=None):
    """Rewrite locals.toml from the scrape, reserving a rogue slice.

    Returns the weights written. The file keeps its explanatory header so
    the next reader knows these are a stand-in for real observation, not
    a measurement of the user's actual room.
    """
    path = Path(path) if path else LOCALS
    shares, _ = scraped_shares(conn, fmt=fmt, top=top)
    if not shares:
        return []

    scale = 1.0 - rogue
    weights = [(name, w * scale) for name, w in shares]
    weights.append(("rogue", rogue))

    meta = (load(path).get("meta") or {})
    lines = [
        "# Who you actually face, not who wins YCS.",
        "#",
        "# AUTO-GENERATED by `daemon.py locals auto` from scraped tournament",
        "# lists. This is a stand-in, not an observation of your room. Each",
        "# deck contributes one unit of weight split across its archetype",
        "# tags, so a four-engine hybrid is not counted as four opponents.",
        "#",
        f"# A {rogue:.0%} slice is reserved for rogue: the scrape only sees decks",
        "# that TOPPED something, and your locals has budget builds and piles",
        "# that never place. Edit these by hand after an event — guessing from",
        "# the room you were actually in beats any scrape.",
        "",
        "[meta]",
        f'format = "{meta.get("format", "Tournament Meta Decks")}"',
        f'window_days = {int(meta.get("window_days", 120))}',
        "",
        "[weights]",
    ]
    for name, w in weights:
        lines.append(f'"{name}" = {w:.4f}')
    path.write_text("\n".join(lines) + "\n")
    return weights
