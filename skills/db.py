"""SQLite schema and connection handling for duelroom."""

import sqlite3
from pathlib import Path

DB_PATH = Path(__file__).resolve().parent.parent / "data" / "duelroom.db"

SCHEMA = """
CREATE TABLE IF NOT EXISTS cards (
    id            INTEGER PRIMARY KEY,
    name          TEXT NOT NULL,
    type          TEXT,
    frame         TEXT,
    race          TEXT,
    attribute     TEXT,
    level         INTEGER,
    atk           INTEGER,
    def           INTEGER,
    linkval       INTEGER,
    scale         INTEGER,
    archetype     TEXT,
    text          TEXT,
    banlist_tcg   TEXT,
    banlist_ocg   TEXT,
    last_fetched  TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cards_name ON cards(name);
CREATE INDEX IF NOT EXISTS idx_cards_archetype ON cards(archetype);

-- Alternate passcodes. YGOPRODeck returns several ids per card (different
-- printings); .ydk files may reference any of them, so every id must resolve.
CREATE TABLE IF NOT EXISTS card_aliases (
    alias_id  INTEGER PRIMARY KEY,
    card_id   INTEGER NOT NULL REFERENCES cards(id)
);

CREATE TABLE IF NOT EXISTS decks (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    archetype   TEXT,          -- longest-match primary; a hint, see deck_tags
    format      TEXT NOT NULL,
    source_url  TEXT,
    title       TEXT,
    placement   TEXT,
    deck_date   TEXT,
    list_hash   TEXT NOT NULL,
    scraped_at  TEXT NOT NULL,
    UNIQUE(list_hash, format)
);
CREATE INDEX IF NOT EXISTS idx_decks_arch ON decks(archetype, format);

-- Archetype labels, many-to-many. A modern list is a hybrid ("Azamina
-- Mitsurugi Dark Magician") and legitimately belongs to several archetype
-- groups at once, so one column on `decks` cannot hold the truth. The
-- `decks.archetype` column keeps the longest-match primary as a hint only.
CREATE TABLE IF NOT EXISTS deck_tags (
    deck_id  INTEGER NOT NULL REFERENCES decks(id) ON DELETE CASCADE,
    tag      TEXT NOT NULL,
    PRIMARY KEY (deck_id, tag)
);
CREATE INDEX IF NOT EXISTS idx_deck_tags_tag ON deck_tags(tag);

CREATE TABLE IF NOT EXISTS deck_cards (
    deck_id  INTEGER NOT NULL REFERENCES decks(id) ON DELETE CASCADE,
    card_id  INTEGER NOT NULL,
    section  TEXT NOT NULL CHECK(section IN ('main','extra','side')),
    copies   INTEGER NOT NULL,
    PRIMARY KEY (deck_id, card_id, section)
);

-- The flex-slot table. Recomputed wholesale per archetype+format.
CREATE TABLE IF NOT EXISTS inclusion (
    archetype    TEXT NOT NULL,
    format       TEXT NOT NULL,
    card_id      INTEGER NOT NULL,
    section      TEXT NOT NULL,
    pct_lists    REAL NOT NULL,
    avg_copies   REAL NOT NULL,
    n_lists      INTEGER NOT NULL,
    computed_at  TEXT NOT NULL,
    PRIMARY KEY (archetype, format, card_id, section)
);

-- Simulation runs. engine/scripts versions are recorded per run because a
-- mismatch changes results silently rather than erroring.
CREATE TABLE IF NOT EXISTS runs (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    deck_hash       TEXT NOT NULL,
    deck_name       TEXT,
    scenario        TEXT NOT NULL,
    seed_base       INTEGER NOT NULL,
    n_trials        INTEGER NOT NULL,
    going_first     INTEGER NOT NULL,
    engine_version  TEXT,
    scripts_version TEXT,
    cdb_version     TEXT,
    started         TEXT NOT NULL,
    finished        TEXT
);

CREATE TABLE IF NOT EXISTS trials (
    id               INTEGER PRIMARY KEY AUTOINCREMENT,
    run_id           INTEGER NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
    -- TEXT, not INTEGER: ygorl's hand seeds are unsigned 64-bit and values
    -- above 2^63-1 overflow SQLite's signed INTEGER. They are identifiers,
    -- never arithmetic, so the string form loses nothing.
    seed             TEXT NOT NULL,
    opening_hand     TEXT NOT NULL,
    completed        INTEGER NOT NULL,
    board_score      REAL,
    negates          INTEGER,
    special_summons  INTEGER,
    line             TEXT
);
CREATE INDEX IF NOT EXISTS idx_trials_run ON trials(run_id);

-- End-board library generated by goldfishing meta decks going first.
CREATE TABLE IF NOT EXISTS boards (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    archetype   TEXT NOT NULL,
    format      TEXT NOT NULL,
    board_state TEXT NOT NULL,
    frequency   REAL NOT NULL,
    negates     INTEGER,
    source_run  INTEGER REFERENCES runs(id)
);
CREATE INDEX IF NOT EXISTS idx_boards_arch ON boards(archetype, format);

-- Point-in-time copies of `inclusion`, so tech cards rising or falling
-- can be seen across scrapes. Drift needs TIME, not a bigger single
-- scrape: the stored lists skew heavily to when they were last updated
-- (274 in one month, 25 in the most recent 30 days), so slicing one
-- scrape by date gives 2-5 lists per archetype and measures noise.
CREATE TABLE IF NOT EXISTS inclusion_history (
    label        TEXT NOT NULL,
    archetype    TEXT NOT NULL,
    format       TEXT NOT NULL,
    card_id      INTEGER NOT NULL,
    section      TEXT NOT NULL,
    pct_lists    REAL NOT NULL,
    avg_copies   REAL NOT NULL,
    n_lists      INTEGER NOT NULL,
    captured_at  TEXT NOT NULL,
    PRIMARY KEY (label, archetype, format, card_id, section)
);
CREATE INDEX IF NOT EXISTS idx_incl_hist ON inclusion_history(archetype, label);

-- Work queued by the web UI and executed by a single worker process.
-- One worker means one solver job at a time by construction: the engine
-- takes 6 of 8 cores, and two concurrent sweeps make both slower and
-- the machine unusable.
CREATE TABLE IF NOT EXISTS jobs (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    kind        TEXT NOT NULL,
    deck        TEXT,
    params      TEXT NOT NULL DEFAULT '{}',
    state       TEXT NOT NULL DEFAULT 'queued'
                CHECK(state IN ('queued','running','done','failed','cancelled')),
    log_path    TEXT,
    pid         INTEGER,
    progress    TEXT,
    error       TEXT,
    queued_at   TEXT NOT NULL,
    started_at  TEXT,
    finished_at TEXT
);
CREATE INDEX IF NOT EXISTS idx_jobs_state ON jobs(state, id);

CREATE TABLE IF NOT EXISTS meta (
    key    TEXT PRIMARY KEY,
    value  TEXT
);
"""


def connect(path=None):
    """Open the database, creating the schema if needed."""
    path = Path(path) if path else DB_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA journal_mode = WAL")
    conn.executescript(SCHEMA)
    return conn


def get_meta(conn, key, default=None):
    row = conn.execute("SELECT value FROM meta WHERE key = ?", (key,)).fetchone()
    return row["value"] if row else default


def set_meta(conn, key, value):
    conn.execute(
        "INSERT INTO meta (key, value) VALUES (?, ?) "
        "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
        (key, str(value)),
    )
